import {fireEvent,render,screen,waitFor} from '@testing-library/react'
import {beforeEach,expect,it,vi} from 'vitest'
import '../manual/dialogTestSetup'
import DemoApp from './DemoApp'
import {startDemoSession,resetDemoSession} from './session'
import {ApiError} from '../api/client'
vi.mock('./session',()=>({startDemoSession:vi.fn(),resetDemoSession:vi.fn()}))
vi.mock('./DemoManual',()=>({DemoManual:({role,navigate}:{role:string;navigate:(url:string)=>void})=><div>매뉴얼 목록 <button onClick={()=>navigate(role==='OWNER'?'/author':'/questions')}>다음 체험</button></div>}))
vi.mock('../manual/ManualAuthoring',()=>({ManualAuthoring:({onBack}:{onBack:()=>void})=><div>AI 인터뷰 <button onClick={onBack}>완성본 확인</button></div>}))
vi.mock('../qa/QaChat',()=>({QaChat:({conversationId,onCreated}:{conversationId:string;onCreated:(id:string)=>void})=><div>AI 질문 {conversationId}<button onClick={()=>onCreated('00000000-0000-0000-0000-000000000001')}>질문 보내기</button></div>}))
const visitor=(role:'OWNER'|'WORKER',fresh=false)=>({role,storeId:'00000000-0000-0000-0000-000000000002',expiresAt:'2099-01-01T00:00:00Z',csrfToken:'token',fresh})
beforeEach(()=>{
 window.history.replaceState(null,'','/')
 vi.mocked(startDemoSession).mockReset();vi.mocked(resetDemoSession).mockReset()
})
it('enters worker manual and contains direct URLs, navigation, and history in demo scope',async()=>{
 window.history.replaceState(null,'','/home?view=jobs')
 vi.mocked(startDemoSession).mockResolvedValue(visitor('WORKER'))
 render(<DemoApp role="WORKER"/>)
 await screen.findByText('매뉴얼 목록')
 expect(window.location.pathname).toBe('/manual')
 expect(screen.queryByText('로그인')).not.toBeInTheDocument()
 fireEvent.click(screen.getByText('다음 체험'));expect(await screen.findByText('AI 질문')).toBeInTheDocument()
 fireEvent.click(screen.getByText('질문 보내기'))
 expect(window.location.search).toContain('id=00000000-0000-0000-0000-000000000001')
 window.history.replaceState(null,'','/signup');fireEvent.popState(window)
 expect(await screen.findByText('매뉴얼 목록')).toBeInTheDocument()
 expect(window.location.pathname).toBe('/manual')
})
it('enters owner authoring and provides published preview within its routes',async()=>{
 vi.mocked(startDemoSession).mockResolvedValue(visitor('OWNER'))
 render(<DemoApp role="OWNER"/>)
 expect(await screen.findByText('AI 인터뷰')).toBeInTheDocument()
 expect(window.location.pathname).toBe('/author')
 fireEvent.click(screen.getByText('완성본 확인'));expect(await screen.findByText('매뉴얼 목록')).toBeInTheDocument()
 expect(window.location.pathname).toBe('/manual')
})
it('restores a conversation URL only for a resumed session',async()=>{
 const id='00000000-0000-0000-0000-000000000001'
 window.history.replaceState(null,'',`/questions?id=${id}`)
 vi.mocked(startDemoSession).mockResolvedValue(visitor('WORKER'))
 const app=render(<DemoApp role="WORKER"/>)
 expect(await screen.findByText(`AI 질문 ${id}`)).toBeInTheDocument()
 app.unmount()
 vi.mocked(startDemoSession).mockResolvedValue(visitor('WORKER',true))
 render(<DemoApp role="WORKER"/>)
 expect(await screen.findByText('매뉴얼 목록')).toBeInTheDocument()
 expect(window.location.search).toBe('')
})
it('canceling reset sends nothing; failed reset preserves the current experience',async()=>{
 vi.mocked(startDemoSession).mockResolvedValue(visitor('OWNER'))
 render(<DemoApp role="OWNER"/>);await screen.findByText('AI 인터뷰')
 fireEvent.click(screen.getByText('다시 체험'));fireEvent.click(screen.getByText('취소'))
 expect(resetDemoSession).not.toHaveBeenCalled()
 vi.mocked(resetDemoSession).mockRejectedValue(new ApiError(0,'NETWORK_ERROR'))
 fireEvent.click(screen.getByText('다시 체험'));fireEvent.click(screen.getByText('새 체험 시작'))
 await screen.findByRole('alert')
 expect(screen.getByText('AI 인터뷰')).toBeInTheDocument()
 fireEvent.click(screen.getByText('취소'))
 expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})
it('successful reset clears old route and workspace and waits for confirmation',async()=>{
 vi.mocked(startDemoSession).mockResolvedValue(visitor('WORKER'))
 vi.mocked(resetDemoSession).mockResolvedValue({...visitor('WORKER',true),csrfToken:'next'})
 render(<DemoApp role="WORKER"/>);await screen.findByText('매뉴얼 목록')
 fireEvent.click(screen.getByText('다음 체험'));await screen.findByText('AI 질문')
 fireEvent.click(screen.getByText('다시 체험'))
 expect(resetDemoSession).not.toHaveBeenCalled()
 fireEvent.click(screen.getByText('새 체험 시작'))
 await waitFor(()=>expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
 expect(screen.getByText('매뉴얼 목록')).toBeInTheDocument()
 expect(window.location.pathname).toBe('/manual')
})
it('shows bootstrap retry and rejects unknown demo hosts without auth UI',async()=>{
 const app=render(<DemoApp role={null}/>)
 expect(screen.getByText('데모 주소를 확인해 주세요')).toBeInTheDocument()
 expect(startDemoSession).not.toHaveBeenCalled();app.unmount()
 vi.mocked(startDemoSession).mockRejectedValueOnce(new ApiError(0,'NETWORK_ERROR')).mockResolvedValueOnce(visitor('OWNER'))
 render(<DemoApp role="OWNER"/>);await screen.findByRole('alert')
 fireEvent.click(screen.getByText('다시 연결하기'))
 expect(await screen.findByText('AI 인터뷰')).toBeInTheDocument()
})
it('starts a fresh experience after expiry and clears the previous conversation',async()=>{
 vi.mocked(startDemoSession).mockResolvedValueOnce(visitor('WORKER')).mockResolvedValueOnce({...visitor('WORKER',true),csrfToken:'new'})
 window.history.replaceState(null,'','/questions?id=00000000-0000-0000-0000-000000000001')
 render(<DemoApp role="WORKER"/>);await screen.findByText('AI 질문 00000000-0000-0000-0000-000000000001')
 fireEvent(window,new Event('jidan-session-expired'));await screen.findByText('체험 시간이 끝났어요')
 fireEvent.click(screen.getByText('새 체험 시작'))
 expect(await screen.findByText('매뉴얼 목록')).toBeInTheDocument()
 expect(window.location.search).toBe('')
 expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})
